// Generates src/data/icons.ts: path data for the Material Symbols the site uses (the same icon family as the KoBar app)
// and a few brand marks from Simple Icons. The packages are not project dependencies; install them anywhere and pass
// that node_modules folder:
//
//   npm install --prefix <tmp> @material-symbols/svg-300 simple-icons
//   node scripts/gen-icons.mjs <tmp>/node_modules
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const modules = process.argv[2];
if (!modules) {
  console.error('usage: node scripts/gen-icons.mjs <node_modules folder>');
  process.exit(1);
}

// Plugin manifests name icons by their Material Symbols ligature. A few ligatures were renamed in the SVG set.
const SVG_NAME = { push_pin: 'keep', expand_more: 'keyboard_arrow_down' };

const SYMBOLS = [
  // plugin manifest icons
  'content_paste', 'apps', 'smart_toy', 'calculate', 'palette', 'hourglass_empty', 'inventory_2',
  'calendar_month', 'music_note', 'push_pin', 'screenshot_region', 'library_books', 'format_list_bulleted',
  // interface
  'menu', 'close', 'play_arrow', 'download', 'dock_to_right', 'sticky_note_2', 'workspaces', 'tune',
  'settings_backup_restore', 'translate', 'keyboard', 'shield', 'no_accounts', 'key', 'verified_user', 'code',
  'favorite', 'forum', 'storefront', 'update', 'check', 'expand_more', 'mail', 'arrow_outward', 'extension',
  'arrow_back', 'arrow_forward', 'layers', 'desktop_windows', 'folder_open', 'gpp_maybe', 'visibility', 'notifications',
];

const BRANDS = ['github', 'discord', 'reddit', 'x', 'youtube', 'patreon', 'opencollective'];

const pathOf = (svg) => {
  const d = [...svg.matchAll(/<path[^>]*\sd="([^"]+)"/g)].map((m) => m[1]);
  if (d.length === 0) throw new Error('no <path> in svg');
  return d.join(' ');
};

const symbolDir = path.join(modules, '@material-symbols', 'svg-300', 'outlined');
const symbolVersion = JSON.parse(readFileSync(path.join(modules, '@material-symbols', 'svg-300', 'package.json'), 'utf8')).version;
const brandDir = path.join(modules, 'simple-icons', 'icons');
const brandVersion = JSON.parse(readFileSync(path.join(modules, 'simple-icons', 'package.json'), 'utf8')).version;

const symbols = SYMBOLS.map((name) => [name, pathOf(readFileSync(path.join(symbolDir, `${SVG_NAME[name] ?? name}.svg`), 'utf8'))]);
const brands = BRANDS.map((name) => [name, pathOf(readFileSync(path.join(brandDir, `${name}.svg`), 'utf8'))]);

const out = `// Generated by scripts/gen-icons.mjs. Do not edit by hand.
// Material Symbols Outlined, weight 300 (@material-symbols/svg-300 ${symbolVersion}, Apache License 2.0), viewBox "0 -960 960 960".
// Brand marks from Simple Icons ${brandVersion} (CC0 1.0), viewBox "0 0 24 24".

export const symbols = {
${symbols.map(([n, d]) => `  ${n}: '${d}',`).join('\n')}
} as const;

export type SymbolName = keyof typeof symbols;

export const brands = {
${brands.map(([n, d]) => `  ${n}: '${d}',`).join('\n')}
} as const;

export type BrandName = keyof typeof brands;
`;

writeFileSync(path.join(import.meta.dirname, '..', 'src', 'data', 'icons.ts'), out);
console.log(`icons.ts: ${symbols.length} symbols, ${brands.length} brands`);
